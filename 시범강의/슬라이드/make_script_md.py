# script.json → 강의 스크립트 문서(../02_드론이란_시범강의_스크립트.md) 생성
import json, re, pathlib
here = pathlib.Path(__file__).parent
S = json.loads((here / "script.json").read_text(encoding="utf-8"))
syll = lambda t: len(re.findall(r"[가-힣0-9]", re.sub(r"\(▶[^)]*\)", "", t)))
total = sum(syll(s["script"]) for s in S)
clicks = sum(s["script"].count("▶") for s in S)
L = ["# [시범강의] 드론이란? — 강의 스크립트", "",
     "> 대상: 담당자·심사위원 앞 10분 시범강의 (강의식, 발표자 스피치만으로 진행)",
     "> 함께 쓰는 자료: `드론이란_시범강의.html` (8장) · 대본은 슬라이드 화면에 나오지 않으니 이 문서를 따로 띄우거나 인쇄해서 보세요",
     f"> 분량: 약 {total:,}음절 · 클릭 {clicks}번 · 보통 발표 속도(1초에 4.5음절)로 약 {total / 4.5 / 60:.1f}분 + 슬라이드를 넘길 때 쉬는 시간 ≈ 10분", "",
     "## 읽는 법", "",
     "- **(▶ 클릭)** 표시에서 클릭하거나 → 키를 누르면, 흐릿하게 보이던 내용이 선명하게 나타나요. 단계 공개는 2번(카드 4장)과 5번(공통점 태그) 슬라이드에만 있고, 나머지 슬라이드는 → 키로 바로 넘깁니다.",
     "- 질문 형태의 문장은 답을 기다리지 않고 바로 이어서 말하는 **수사 의문문**이에요.",
     "- 1번 슬라이드의 강사 소개 문장(경력)은 실제 내용으로 바꿔 말하세요. 슬라이드의 이름·직함·사진은 `슬라이드/instructor.json`에서 고칠 수 있어요.", "",
     "## 한눈에 보기", "", "| 슬라이드 | 제목 | 시간 | 클릭 |", "|---|---|---|---|"]
for s in S:
    L.append(f"| {s['slide']} | {s['title']} | {s['time']} | {s['script'].count('▶')}번 |")
L += ["", "**핵심 메시지:** 드론은 하늘을 나는 컴퓨터이고, 이제는 스스로 생각하는 드론의 시대다.", "", "---", ""]
for s in S:
    L += [f"## 슬라이드 {s['slide']}. {s['title']}", "", f"- **시간:** {s['time']}", f"- **화면·동작:** {s['action']}", "", "**대본**", ""]
    for line in s["script"].split("\n"):
        line = re.sub(r"(\(▶[^)]*\))", r"**\1**", line)
        L += [f"> {line}", ">"]
    L.pop()
    L += ["", f"**포인트:** {s['point']}", "", "---", ""]
L += ["## 시간 조절 팁", "",
      "| 상황 | 대응 |", "|---|---|",
      "| 시간이 부족할 때 | 슬라이드 5의 사례 설명을 첫 문장만 말하고, 슬라이드 6의 각 장점 뒤 덧붙이는 문장을 생략합니다 (약 1분 단축) |",
      "| 시간이 남을 때 | 슬라이드 4에서 이글 드론 사진의 프로펠러·몸체 위치를 직접 짚어 가며 설명합니다 |",
      "| 학교급별 조절 | 기획안(`01_드론이란_10분_시범강의_기획안.md`)의 학교급별 조절표를 참고해 예시와 설명 깊이만 바꿉니다 |", ""]
(here.parent / "02_드론이란_시범강의_스크립트.md").write_text("\n".join(L), encoding="utf-8")
print("written", total, "syllables", clicks, "clicks")
